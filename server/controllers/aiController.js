exports.getWeakTopics = catchAsync(async (req, res) => {
  const results = await QuizResult.find({ student: req.userId, status: 'completed' })
    .populate('quiz', 'title')
    .sort('-createdAt');

  const topicPerformance = {};
  results.forEach((r) => {
    const t = r.quiz?.title?.split(' ')[0] || 'General';
    if (!topicPerformance[t]) topicPerformance[t] = { total: 0, earned: 0, attempts: 0 };
    topicPerformance[t].total += r.totalPoints;
    topicPerformance[t].earned += r.earnedPoints;
    topicPerformance[t].attempts += 1;
  });

  const weakTopics = Object.entries(topicPerformance)
    .map(([topic, perf]) => ({
      topic,
      score: perf.total > 0 ? Math.round((perf.earned / perf.total) * 100) : 0,
      attempts: perf.attempts,
      isWeak: perf.total > 0 ? (perf.earned / perf.total) * 100 < 60 : true,
    }))
    .sort((a, b) => a.score - b.score);

  res.status(200).json({ success: true, data: weakTopics });
});

exports.generateFromLesson = catchAsync(async (req, res) => {
  const { lessonId, difficulty, count, type } = req.body;
  const lesson = await Lesson.findById(lessonId);
  if (!lesson) throw new AppError('Lesson not found', 404);

  const content = [lesson.title, lesson.description, lesson.content?.textContent || ''].filter(Boolean).join('\n');

  const quiz = await aiService.generateQuiz({
    topic: lesson.title,
    difficulty: difficulty || 'intermediate',
    count: Math.min(count || 5, 20),
    type: type || 'mcq',
    content,
    timeLimit: 15,
  });

  res.status(200).json({
    success: true,
    data: { ...quiz, lessonId, source: 'lesson' },
    message: 'Quiz generated from lesson content',
  });
});

